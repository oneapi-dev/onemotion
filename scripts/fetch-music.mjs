// Fetches and prepares OneMotion's built-in music library.
//
//   node scripts/fetch-music.mjs
//
// scripts/music.json lists each track (FreePD, CC0 1.0) with the SHA-256 of
// its source file. Every download is checked against it, then the first
// `seconds` are loudness-normalized (-16 LUFS), faded out over the last four
// seconds and encoded as 96 kbps MP3. Writes:
//
//   public/music/<id>.mp3
//   public/music/CREDITS.md
//   src/music/library.ts          the manifest the films read (generated)
//
// Downloads are cached in node_modules/.cache/freepd, so a rerun only encodes.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "public", "music");
const CACHE = join(ROOT, "node_modules", ".cache", "freepd");
const MANIFEST = join(ROOT, "src", "music", "library.ts");
const doc = JSON.parse(readFileSync(join(ROOT, "scripts", "music.json"), "utf8"));

function findFfmpeg() {
  const dir = join(ROOT, "node_modules", "@remotion");
  for (const name of readdirSync(dir)) {
    if (!name.startsWith("compositor-")) continue;
    for (const bin of ["ffmpeg.exe", "ffmpeg"]) if (existsSync(join(dir, name, bin))) return join(dir, name, bin);
  }
  throw new Error("No ffmpeg found under node_modules/@remotion/compositor-*. Run npm install.");
}

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

async function download(track) {
  const cached = join(CACHE, `${track.sha256}.mp3`);
  if (existsSync(cached)) return cached;
  const url = doc.source.mirror + track.path.split("/").map(encodeURIComponent).join("/");
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const bytes = Buffer.from(await res.arrayBuffer());
  const got = sha256(bytes);
  if (got !== track.sha256) throw new Error(`${track.path}: SHA-256 ${got} does not match the manifest's ${track.sha256}`);
  mkdirSync(CACHE, { recursive: true });
  writeFileSync(cached, bytes);
  return cached;
}

const ffmpeg = findFfmpeg();
const S = doc.seconds;
mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) if (f.endsWith(".mp3")) rmSync(join(OUT, f));

for (const t of doc.tracks) {
  const src = await download(t);
  const fade = `volume='if(gt(t,${S - 4}),max(0,(${S}-t)/4),1)':eval=frame`;
  execFileSync(ffmpeg, ["-y", "-v", "error", "-i", src, "-t", String(S), "-af", `loudnorm=I=-16:TP=-1.5:LRA=11,${fade}`, "-ar", "44100", "-ac", "2", "-c:a", "libmp3lame", "-b:a", "96k", join(OUT, `${t.id}.mp3`)]);
  console.log(`wrote public/music/${t.id}.mp3`);
}

const entries = doc.tracks.map((t) => ({ id: t.id, title: t.title, artist: t.artist, mood: t.mood, tags: t.tags, bpm: t.bpm, firstBeat: t.firstBeat, seconds: S }));
writeFileSync(
  MANIFEST,
  `// Generated by scripts/fetch-music.mjs from scripts/music.json. Do not edit by hand.

/** A built-in music track: public/music/<id>.mp3, ${S} s long, loudness-normalized, faded out at the end. */
export type LibraryTrack = {
  id: string;
  title: string;
  artist: string;
  /** What it sounds like, in FreePD's words. */
  mood: string;
  tags: string[];
  /** Its tempo, and where its first beat falls (seconds), measured from the audio. */
  bpm: number;
  firstBeat: number;
  seconds: number;
};

/** ${doc.source.name}, ${doc.source.license}. */
export const LIBRARY: LibraryTrack[] = ${JSON.stringify(entries, null, 2)};
`,
);
console.log("wrote src/music/library.ts");

writeFileSync(
  join(OUT, "CREDITS.md"),
  `# Built-in music

All tracks are from [${doc.source.name}](https://freepd.com/) and are dedicated to the public domain under
[${doc.source.license}](${doc.source.license_url}). No attribution is required; we credit the composers anyway.

${doc.source.note}

Each file is the first ${S} seconds of the original, loudness-normalized and faded out.

| File | Title | Composer | Source SHA-256 |
| --- | --- | --- | --- |
${doc.tracks.map((t) => `| ${t.id}.mp3 | ${t.title} | ${t.artist} | \`${t.sha256.slice(0, 16)}…\` |`).join("\n")}
`,
);
console.log("wrote public/music/CREDITS.md");
